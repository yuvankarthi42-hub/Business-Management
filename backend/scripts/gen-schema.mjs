// Reads server/catalyst/schema.sql (the single source of truth) and writes:
//   backend/src/db/schema.gen.ts  — column types per table, used by every database call
//   backend/setup/tables.json     — the same list, used by the table-creation script and the schema check
// Run: node backend/scripts/gen-schema.mjs   (also runs before every backend build)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { BOTH, PLATFORM } from './placement.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const sql = readFileSync(join(root, 'server/catalyst/schema.sql'), 'utf8')

const tables = {}
for (const m of sql.matchAll(/CREATE TABLE (\w+) \(([\s\S]*?)\n\);/g)) {
  const [, name, body] = m
  const columns = []
  for (const raw of body.split('\n')) {
    const line = raw.replace(/\s+--.*$/, '')
    const c = line.match(/^ {2}(\w+)\s+(VARCHAR\((\d+)\)|(?:TEXT|ENCRYPTED|BIGINT|INT|DOUBLE|BOOLEAN|DATETIME|DATE)\b)(.*)$/)
    if (!c) continue
    const [, col, typeRaw, len, rest] = c
    const comment = raw.includes('--') ? raw.slice(raw.indexOf('--') + 2).trim() : ''
    const type = typeRaw.startsWith('VARCHAR') ? 'varchar' : typeRaw.toLowerCase()
    const fk = rest.match(/FK → (\w+) (CASCADE|NULL)/)
    const def = rest.match(/DEFAULT ('([^']*)'|[\w.-]+)/)
    const enumName = type === 'int' ? (comment.match(/^(\w+):/) || comment.match(/^([A-Z]\w+) \(/) || [])[1] : undefined
    columns.push({
      name: col,
      // BIGINT ids that point at a ROWID without a foreign key (ref_id, entity_id…) stay strings like ROWIDs.
      type: fk ? 'fk' : type === 'bigint' && /_id$/.test(col) ? 'id' : type,
      ...(len ? { maxLength: Number(len) } : {}),
      mandatory: /\bNOT NULL\b/.test(rest),
      unique: /\bUNIQUE\b/.test(rest),
      search: /\bSEARCH\b/.test(rest),
      pii: /\bPII\b/.test(rest),
      ...(def ? { default: def[2] !== undefined ? def[2] : def[1] } : {}),
      ...(fk ? { references: fk[1], onDelete: fk[2] === 'CASCADE' ? 'cascade' : 'null' } : {}),
      ...(enumName && /^[A-Z]/.test(enumName) ? { enum: enumName } : {}),
      // money in paise, qty in thousandths, % in basis points → converted to app units in the mappers
      ...(col.endsWith('_minor') ? { unit: 'minor' } : col.endsWith('_milli') ? { unit: 'milli' } : col.endsWith('_bp') ? { unit: 'bp' } : {}),
    })
  }
  tables[name] = { columns }
}

const names = Object.keys(tables)
for (const t of [...PLATFORM, ...BOTH]) if (!tables[t]) throw new Error(`placement.mjs: unknown table ${t}`)
if (names.length < 50) throw new Error(`Only ${names.length} tables parsed — check schema.sql`)

mkdirSync(join(root, 'backend/src/db'), { recursive: true })
mkdirSync(join(root, 'backend/setup'), { recursive: true })
writeFileSync(join(root, 'backend/setup/tables.json'), JSON.stringify(tables, null, 2) + '\n')
const ts = `// GENERATED by backend/scripts/gen-schema.mjs from server/catalyst/schema.sql — do not edit by hand.
export type ColumnType = 'varchar' | 'text' | 'encrypted' | 'bigint' | 'int' | 'double' | 'boolean' | 'datetime' | 'date' | 'fk' | 'id'
export interface ColumnDef { name: string; type: ColumnType; maxLength?: number; mandatory: boolean; unique: boolean; search: boolean; pii: boolean; default?: string; references?: string; onDelete?: 'cascade' | 'null'; enum?: string; unit?: 'minor' | 'milli' | 'bp' }
export const TABLES = ${JSON.stringify(Object.fromEntries(names.map((n) => [n, tables[n].columns])), null, 0)} as const satisfies Record<string, readonly ColumnDef[]>
export type TableName = keyof typeof TABLES
/** Where a table lives with one database per shop (see backend/scripts/placement.mjs). */
export const PLATFORM_TABLES: readonly TableName[] = ${JSON.stringify(PLATFORM)}
export const SHARED_TABLES: readonly TableName[] = ${JSON.stringify(BOTH)}
`
writeFileSync(join(root, 'backend/src/db/schema.gen.ts'), ts)
console.log(`schema: ${names.length} tables, ${names.reduce((n, t) => n + tables[t].columns.length, 0)} columns`)
